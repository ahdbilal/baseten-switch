func codexDesktopStore(configPath string) codexdesktop.Store {
	dir := envDefault("UNITY_GATEWAY_CODEX_HOME", envDefault("CODEX_HOME", homeJoin(".codex")))
	store := codexdesktop.Store{Dir: dir, StatePath: filepath.Join(filepath.Dir(configPath), "codex-desktop.json"), RenderProvider: func() (string, error) {
		c, err := unity.Load(configPath)
		if err != nil {
			return "", err
		}
		if c == nil {
			return "", fmt.Errorf("sign in to a Databricks workspace first")
		}
		r, err := c.RenderClient(context.Background(), ugruntime.Request{Client: "codex-desktop", BaseURL: codexdesktop.BaseURL, Provider: codexdesktop.Provider})
		return "\n# Base provider generated by ug " + ugruntime.Revision + "\n" + r.ProviderTOML, err
	}}
	// Pre-workspace installations retain their existing local-only configuration.
	if c, err := unity.Load(configPath); err == nil && c == nil {
		store.RenderProvider = nil
	}
	return store
}
func codexDesktopGatewayConfig(raw []byte, enabled bool, model string) ([]byte, error) {
	var f config.File
	if e := config.UnmarshalStrict(raw, &f); e != nil {
		return nil, e
	}
	var doc yaml.Node
	if e := yaml.Unmarshal(raw, &doc); e != nil {
		return nil, e
	}
	root := doc.Content[0]
	for i := 0; i < len(root.Content); i += 2 {
		if root.Content[i].Value != "clients" {
			continue
		}
		seq := root.Content[i+1]
		if seq.Kind != yaml.SequenceNode {
			return nil, fmt.Errorf("clients must be a list")
		}
		found := -1
		for j, c := range f.Clients {
			if c.Name == codexdesktop.Client {
				if c.BindAddr != "127.0.0.1:45276" || c.ProtocolShape != "openai" {
					return nil, fmt.Errorf("Codex desktop listener conflicts with existing configuration")
				}
				found = j
			} else if strings.HasSuffix(c.BindAddr, ":45276") && enabled {
				return nil, fmt.Errorf("Codex desktop port 45276 is assigned to another client")
			}
		}
		if !enabled {
			if found < 0 {
				return raw, nil
			}
			seq.Content = append(seq.Content[:found], seq.Content[found+1:]...)
		} else {
			var node yaml.Node
			e := node.Encode(map[string]any{"name": codexdesktop.Client, "enabled": true, "bind_addr": "127.0.0.1:45276", "protocol_shape": "openai", "default_model": model, "fallback_route": "openai"})
			if e != nil {
				return nil, e
			}
			if found >= 0 { // Preserve unrelated existing client fields; only enable it.
				for i := 0; i < len(seq.Content[found].Content); i += 2 {
					if seq.Content[found].Content[i].Value == "enabled" {
						seq.Content[found].Content[i+1].Value = "true"
					}
				}
			} else {
				seq.Content = append(seq.Content, &node)
			}
		}
		b, e := yaml.Marshal(&doc)
		if e != nil {
			return nil, e
		}
		if e = config.UnmarshalStrict(b, &f); e != nil {
			return nil, e
		}
		return b, config.ValidateRoutingPolicy(&f)
	}
	return nil, fmt.Errorf("gateway configuration has no clients list")
}
func reloadCodexDesktop(enabled bool, path string) error {
	if state, pid := classifyPidfile(gatewayPidfilePath()); state == pidfileAlive {
		if e := signalRouter(pid); e != nil {
			return e
		}
		if enabled && !waitClientBound(envDefault("UNITY_GATEWAY_ADMIN_ADDR", gateway.DefaultAdminAddr), codexdesktop.Client, routeApplyTimeout) {
			return fmt.Errorf("Codex desktop listener did not start; check port 45276 and retry")
		}
	}
	return nil
}
func codexDesktopCatalog(st codexdesktop.State) ([]byte, error) {
	rows := []map[string]any{}
	for _, m := range st.Models {
		if st.Hidden[m.ID] {
			continue
		}
		rows = append(rows, codexPickerEntry(m.ID, m.Name, 128000, len(rows), nil))
	}
	return json.MarshalIndent(codexPickerCatalog{Owner: "unity-gateway-desktop-v1", Models: rows}, "", "  ")
}
func applyCodexDesktop(store codexdesktop.Store, st codexdesktop.State) error {
	b, e := codexDesktopCatalog(st)
	if e != nil {
		return e
	}
	return store.Apply(st, b)
}
func cmdCodexDesktop(args []string) int {
	if len(args) == 0 {
		return desktopError(fmt.Errorf("usage: unity-gateway codex-desktop on|off|status|refresh|default <model>|visibility <model> on|off|selection <default> <model>..."))
	}
	path, _ := resolveConfigPath()
	store := codexDesktopStore(path)
	st, e := store.Load()
	if e != nil {
		return desktopError(e)
	}
	st.Default = store.SelectedModel(st)
	switch args[0] {
	case "status":
		return desktopError(json.NewEncoder(os.Stdout).Encode(map[string]any{"models": st.Models, "hidden": st.Hidden, "default": st.Default, "connected": store.Active(st), "configured": st.Connected, "base_url": codexdesktop.BaseURL, "directory": store.Dir}))
	case "off":
		if e = store.Disconnect(); e != nil {
			return desktopError(e)
		}
		if !st.ListenerOwned {
			return 0
		}
		snap, e := safefile.Read(path)
		if e != nil || !snap.Exists {
			return desktopError(e)
		}
		b, e := codexDesktopGatewayConfig(snap.Data, false, "")
		if e != nil {
			return desktopError(e)
		}
		if _, e = snap.Replace(b, 0600); e != nil {
			return desktopError(e)
		}
		if e = reloadCodexDesktop(false, path); e != nil {
			return desktopError(e)
		}
		st, e = store.Load()
		if e != nil {
			return desktopError(e)
		}
		st.ListenerOwned = false
		return desktopError(store.Save(st))
	case "on", "refresh":
		if args[0] == "refresh" && !store.Active(st) {
			return desktopError(fmt.Errorf("enable Codex desktop first"))
		}
		c, e := unity.Load(path)
		if e != nil {
			return desktopError(e)
		}
		if c == nil {
			return desktopError(fmt.Errorf("sign in to a Databricks workspace first"))
		}
		ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
		defer cancel()
		models, e := c.Models(ctx)
		if e != nil {
			return desktopError(e)
		}
		st.Models = []codexdesktop.Model{{ID: compass.Model, Name: "Auto(Compass)"}}
		for _, m := range models {
			st.Models = append(st.Models, codexdesktop.Model{ID: m.ID, Name: m.DisplayName})
		}
		if len(st.Models) < 2 {
			return desktopError(fmt.Errorf("workspace has no Responses models"))
		}
		if !st.Has(st.Default) {
			st.Default = compass.Model
		}
		if st.Hidden == nil {
			st.Hidden = map[string]bool{}
		}
		delete(st.Hidden, st.Default)
		snap, e := safefile.Read(path)
		if e != nil {
			return desktopError(e)
		}
		if !st.ListenerOwned {
			var existing config.File
			if e = config.UnmarshalStrict(snap.Data, &existing); e != nil {
				return desktopError(e)
			}
			for _, c := range existing.Clients {
				if c.Name == codexdesktop.Client {
					return desktopError(fmt.Errorf("existing Codex desktop listener is not managed by this integration"))
				}
			}
		}
		st.ListenerOwned = true
		b, e := codexDesktopGatewayConfig(snap.Data, true, st.Models[1].ID)
		if e != nil {
			return desktopError(e)
		}
		written, e := snap.Replace(b, 0600)
		if e != nil {
			return desktopError(e)
		}
		if e = reloadCodexDesktop(true, path); e == nil {
			e = applyCodexDesktop(store, st)
		}
		if e != nil {
			_, restoreErr := written.Replace(snap.Data, 0600)
			if restoreErr != nil {
				e = fmt.Errorf("%w; gateway restore failed: %v", e, restoreErr)
			} else {
				_ = reloadCodexDesktop(false, path)
			}
			return desktopError(e)
		}
		fmt.Println("Codex desktop enabled. Quit and reopen Codex, then start a new chat. Shared defaults also apply to CLI launches without an explicit profile.")
		return 0
	case "default":
		if len(args) != 2 || !st.Has(args[1]) {
			return desktopError(fmt.Errorf("choose a catalog model"))
		}
		st.Default = args[1]
		delete(st.Hidden, st.Default)
	case "visibility":
		if len(args) != 3 || !st.Has(args[1]) || (args[2] != "on" && args[2] != "off") {
			return desktopError(fmt.Errorf("visibility requires a model and on or off"))
		}
		if st.Hidden == nil {
			st.Hidden = map[string]bool{}
		}
		if args[1] == st.Default && args[2] == "off" {
			return desktopError(fmt.Errorf("choose another default first"))
		}
		st.Hidden[args[1]] = args[2] == "off"
	case "selection":
		if len(args) < 3 {
			return desktopError(fmt.Errorf("select a default and at least one model"))
		}
		st.Default = args[1]
		selected := map[string]bool{}
		for _, id := range args[2:] {
			if !st.Has(id) {
				return desktopError(fmt.Errorf("unknown model %s", id))
			}
			selected[id] = true
		}
		if !selected[st.Default] {
			return desktopError(fmt.Errorf("default must be selected"))
		}
		st.Hidden = map[string]bool{}
		for _, m := range st.Models {
			st.Hidden[m.ID] = !selected[m.ID]
		}
	default:
		return desktopError(fmt.Errorf("unknown Codex desktop command"))
	}
	if !store.Active(st) {
		return desktopError(fmt.Errorf("enable Codex desktop first"))
	}
	return desktopError(applyCodexDesktop(store, st))
}
