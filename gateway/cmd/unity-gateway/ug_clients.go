package main

import (
	"context"
	"fmt"
	"strings"

	"unity-gateway/gateway/internal/ugruntime"
	"unity-gateway/gateway/internal/unity"
)

func (a *codexAdapter) ugCodexOverlay(raw []byte) ([]byte, error) {
	c, err := unity.Load(a.configPath)
	if err != nil || c == nil {
		return raw, err
	}
	rendered, err := c.RenderClient(context.Background(), ugruntime.Request{
		Client: "codex", BaseURL: a.desiredURL(), Provider: "databricks", Model: parseCodexOverlay(raw).model,
	})
	if err != nil {
		return nil, err
	}
	prefix, _, found := strings.Cut(string(raw), codexProviderTable)
	if !found || rendered.ProviderTOML == "" {
		return nil, fmt.Errorf("ug returned an invalid Codex provider")
	}
	return []byte(prefix + "# Base provider generated by ug " + ugruntime.Revision + "\n" + rendered.ProviderTOML), nil
}
